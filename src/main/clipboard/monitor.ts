import { createHash } from 'node:crypto'

import { clipboard, nativeImage, powerMonitor, type NativeImage } from 'electron'

import type { AppSettings } from '../../shared/contracts'
import { classifyText, createTextPreview } from './classify'
import { getSourceApp, isExcludedSource } from './source-app'
import type { HistoryRepository } from '../storage/history-repository'

const MAX_TEXT_BYTES = 1_048_576
const MAX_IMAGE_BYTES = 20 * 1_048_576
const IMAGE_FORMAT_PATTERN = /image|png|tiff|jfif|dib/i
const ALWAYS_PRIVATE_FORMATS = [
  'org.nspasteboard.TransientType',
  'org.nspasteboard.ConcealedType',
  'org.nspasteboard.AutoGeneratedType',
  'com.agilebits.onepassword',
  'ExcludeClipboardContentFromMonitorProcessing'
]

function hash(data: Uint8Array): string {
  return createHash('sha256').update(data).digest('hex')
}

function imageThumbnail(image: NativeImage): string | undefined {
  const { width, height } = image.getSize()
  if (!width || !height) return undefined
  const scale = Math.min(1, 96 / Math.max(width, height))
  const thumbnail = image.resize({
    width: Math.max(1, Math.round(width * scale)),
    height: Math.max(1, Math.round(height * scale)),
    quality: 'good'
  })
  return `data:image/png;base64,${thumbnail.toPNG().toString('base64')}`
}

export class ClipboardMonitor {
  private timer?: NodeJS.Timeout
  private running = false
  private paused = false
  private lastObservedDigest?: string
  private suppressedDigest?: string
  private suppressionExpiresAt = 0
  private lastChangeAt = Date.now()
  private fastUntil = Date.now() + 30_000

  constructor(
    private readonly history: HistoryRepository,
    private readonly getSettings: () => AppSettings,
    private readonly onChange: () => void
  ) {}

  start(skipCurrentClipboard = false): void {
    if (this.running) return
    if (skipCurrentClipboard) this.rememberCurrentClipboard()
    this.running = true
    this.schedule(100)
  }

  stop(): void {
    this.running = false
    if (this.timer) clearTimeout(this.timer)
    this.timer = undefined
  }

  setPaused(paused: boolean): void {
    const wasPaused = this.paused
    this.paused = paused
    if (paused && this.timer) {
      clearTimeout(this.timer)
      this.timer = undefined
    }
    if (wasPaused && !paused) {
      this.rememberCurrentClipboard()
      this.wake()
    }
  }

  isPaused(): boolean {
    return this.paused
  }

  wake(): void {
    this.fastUntil = Date.now() + 30_000
    if (this.running) {
      if (this.timer) clearTimeout(this.timer)
      this.schedule(50)
    }
  }

  suppress(data: Uint8Array): void {
    const digest = hash(data)
    this.suppressedDigest = digest
    this.suppressionExpiresAt = Date.now() + 3000
    this.lastObservedDigest = digest
  }

  private schedule(delay = this.nextDelay()): void {
    if (!this.running || this.paused) return
    this.timer = setTimeout(() => {
      void this.tick()
        .catch((error: unknown) => {
          const message = error instanceof Error ? error.message : 'Unknown capture error'
          console.error(`[Keypt] Clipboard capture failed: ${message}`)
        })
        .finally(() => this.schedule())
    }, delay)
    this.timer.unref()
  }

  private nextDelay(): number {
    if (Date.now() < this.fastUntil) return 400
    if (powerMonitor.getSystemIdleTime() > 60) return 2500
    const age = Date.now() - this.lastChangeAt
    if (age < 120_000) return 650
    if (age < 600_000) return 1200
    return 2000
  }

  private async tick(): Promise<void> {
    if (this.paused) return

    const formats = clipboard.availableFormats('clipboard')
    if (this.hasPrivateMarker(formats)) return

    const hasImage = formats.some((format) => IMAGE_FORMAT_PATTERN.test(format))
    if (hasImage) {
      const image = clipboard.readImage('clipboard')
      if (!image.isEmpty()) {
        await this.captureImage(image)
        return
      }
    }

    const text = clipboard.readText('clipboard')
    if (text) await this.captureText(text)
  }

  private rememberCurrentClipboard(): void {
    const formats = clipboard.availableFormats('clipboard')
    if (this.hasPrivateMarker(formats)) return

    if (formats.some((format) => IMAGE_FORMAT_PATTERN.test(format))) {
      const image = clipboard.readImage('clipboard')
      if (!image.isEmpty()) {
        this.lastObservedDigest = hash(image.toPNG())
        return
      }
    }

    const text = clipboard.readText('clipboard')
    this.lastObservedDigest = text ? hash(Buffer.from(text, 'utf8')) : undefined
  }

  private hasPrivateMarker(formats: string[]): boolean {
    if (
      formats.some((format) =>
        ALWAYS_PRIVATE_FORMATS.some((privateFormat) =>
          format.toLocaleLowerCase().includes(privateFormat.toLocaleLowerCase())
        )
      )
    ) {
      return true
    }

    const historyFlag = formats.find((format) =>
      format.toLocaleLowerCase().includes('canincludeinclipboardhistory')
    )
    if (!historyFlag) return false

    const value = clipboard.readBuffer(historyFlag)
    return value.byteLength > 0 && value.every((byte) => byte === 0)
  }

  private async captureText(text: string): Promise<void> {
    const payload = Buffer.from(text, 'utf8')
    if (!payload.byteLength || payload.byteLength > MAX_TEXT_BYTES) return

    const digest = hash(payload)
    if (this.shouldIgnoreDigest(digest)) return
    this.lastObservedDigest = digest
    this.lastChangeAt = Date.now()

    const source = await getSourceApp()
    const settings = this.getSettings()
    if (isExcludedSource(source, settings.excludedApps)) return

    const classification = classifyText(text)
    await this.history.add(
      {
        kind: classification.kind,
        payload,
        preview: createTextPreview(text),
        searchText: text,
        colorValue: classification.colorValue,
        sourceApp: source.name
      },
      settings
    )
    this.onChange()
  }

  private async captureImage(image: NativeImage): Promise<void> {
    const payload = image.toPNG()
    if (!payload.byteLength || payload.byteLength > MAX_IMAGE_BYTES) return

    const digest = hash(payload)
    if (this.shouldIgnoreDigest(digest)) return
    this.lastObservedDigest = digest
    this.lastChangeAt = Date.now()

    const source = await getSourceApp()
    const settings = this.getSettings()
    if (isExcludedSource(source, settings.excludedApps)) return

    const { width, height } = image.getSize()
    const preview = `${width} × ${height} image`
    await this.history.add(
      {
        kind: 'image',
        payload,
        preview,
        searchText: `${preview} ${source.name}`,
        thumbnailDataUrl: imageThumbnail(image),
        sourceApp: source.name
      },
      settings
    )
    this.onChange()
  }

  private shouldIgnoreDigest(digest: string): boolean {
    if (digest === this.lastObservedDigest) return true
    if (Date.now() > this.suppressionExpiresAt) this.suppressedDigest = undefined
    return digest === this.suppressedDigest
  }
}

export function imageFromPayload(payload: Buffer): NativeImage {
  return nativeImage.createFromBuffer(payload)
}
